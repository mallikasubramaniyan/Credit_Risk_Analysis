SELECT * FROM loan_data ORDER BY SK_ID_CURR;
-- Q2
SELECT SK_ID_CURR, NAME_CONTRACT_TYPE, NAME_CONTRACT_STATUS FROM loan_data ORDER BY SK_ID_CURR;
-- Q3
SELECT * FROM loan_data WHERE NAME_CONTRACT_STATUS = 'Approved' ORDER BY SK_ID_CURR;
-- Q4
SELECT * FROM loan_data WHERE NAME_CONTRACT_STATUS = 'Refused' ORDER BY SK_ID_CURR;
-- Q5
SELECT * FROM loan_data WHERE NAME_CLIENT_TYPE = 'Repeater' ORDER BY SK_ID_CURR;
-- Q6
SELECT COUNT(*) AS total_applications FROM loan_data;
-- Q7
SELECT SUM(AMT_CREDIT) AS total_credit FROM loan_data;
-- Q8
SELECT ROUND(AVG(AMT_APPLICATION), 2) AS avg_application FROM loan_data;
-- Q9
SELECT NAME_CONTRACT_STATUS, COUNT(*) AS total FROM loan_data GROUP BY NAME_CONTRACT_STATUS;
-- Q10
SELECT NAME_CONTRACT_TYPE, ROUND(AVG(AMT_ANNUITY), 2) AS avg_annuity FROM loan_data GROUP BY NAME_CONTRACT_TYPE;
-- Q11
SELECT * FROM loan_data WHERE AMT_CREDIT > 500000 ORDER BY SK_ID_CURR;
-- Q12
SELECT * FROM loan_data WHERE AMT_DOWN_PAYMENT > 50000 ORDER BY SK_ID_CURR;
-- Q13
SELECT NAME_CLIENT_TYPE, COUNT(*) AS total FROM loan_data GROUP BY NAME_CLIENT_TYPE;
-- Q14
SELECT NAME_CONTRACT_STATUS, ROUND(AVG(AMT_CREDIT), 2) AS avg_credit FROM loan_data GROUP BY NAME_CONTRACT_STATUS;
-- Q15
SELECT PRODUCT_COMBINATION, COUNT(*) AS total FROM loan_data GROUP BY PRODUCT_COMBINATION ORDER BY total DESC LIMIT 5;
-- Q16
SELECT NAME_CONTRACT_STATUS, SUM(AMT_CREDIT) AS total_credit FROM loan_data WHERE NAME_CONTRACT_STATUS IN ('Approved', 'Refused') GROUP BY NAME_CONTRACT_STATUS;
-- Q17
SELECT NAME_CONTRACT_TYPE, ROUND(AVG(AMT_CREDIT), 2) AS avg_credit FROM loan_data GROUP BY NAME_CONTRACT_TYPE ORDER BY avg_credit DESC LIMIT 3;
-- Q18
SELECT NAME_PAYMENT_TYPE, SUM(AMT_APPLICATION) AS total_application FROM loan_data GROUP BY NAME_PAYMENT_TYPE;
-- Q19
SELECT NAME_SELLER_INDUSTRY, SUM(AMT_CREDIT) AS total_credit FROM loan_data GROUP BY NAME_SELLER_INDUSTRY ORDER BY total_credit DESC LIMIT 5;
-- Q20
SELECT NAME_CONTRACT_TYPE, ROUND(SUM(NAME_CONTRACT_STATUS = 'Approved') * 100.0 / COUNT(*), 2) AS approval_pct FROM loan_data GROUP BY NAME_CONTRACT_TYPE;